BEGIN;
SELECT plan(11);
CREATE TEMP TABLE _host AS SELECT public.atina_create_room('Host 009',4) AS value;
CREATE TEMP TABLE _guest AS SELECT public.atina_join_room('Guest 009',(SELECT value->>'code' FROM _host)) AS value;
SELECT public.atina_set_room_ready((SELECT (value->>'room_id')::uuid FROM _guest),(SELECT value->>'token' FROM _guest),true);
SELECT public.atina_start_room((SELECT (value->>'room_id')::uuid FROM _host),(SELECT value->>'token' FROM _host));

CREATE TEMP TABLE _started AS
SELECT public.atina_start_room_challenges(
  (SELECT (value->>'room_id')::uuid FROM _host),
  (SELECT value->>'token' FROM _host),
  'medium',60,NULL
) AS value;

SELECT is((SELECT value->>'status' FROM _started),'started','host starts a server-generated challenge queue');
SELECT ok((SELECT (value->>'queue_length')::integer > 0 FROM _started),'server selects eligible challenges');
SELECT is((SELECT value->'state'->>'mode' FROM _started),'challenges','public state identifies challenge mode');
SELECT ok((SELECT NOT ((value->'state') ? 'queue') FROM _started),'public state does not disclose the private queue');
SELECT ok((SELECT NOT ((value->'state') ? 'answer') AND NOT ((value->'state') ? 'accepted_answers') FROM _started),'public state does not disclose answer fields');
SELECT is((SELECT jsonb_array_length(value->'state'->'clues') FROM _started),1,'only the first clue is initially revealed');
SELECT ok((SELECT (value->'state'->>'deadline')::numeric > extract(epoch FROM clock_timestamp())*1000 FROM _started),'deadline is generated by the server clock');
SELECT ok((SELECT cardinality(challenge_queue)=(SELECT (value->>'queue_length')::integer)
  FROM private.atina_room_game_state
  WHERE room_id=(SELECT (value->>'room_id')::uuid FROM _host)),'private state stores the complete queue');
SELECT throws_ok(
  format('SELECT public.atina_start_room_challenges(%L::uuid,%L,%L,60,NULL)',
    (SELECT value->>'room_id' FROM _host),(SELECT value->>'token' FROM _guest),'medium'),
  'P0001','Só o anfitrião pode iniciar os desafios.','guest cannot initialize the challenge queue'
);
SELECT throws_ok(
  format('SELECT public.atina_start_room_challenges(%L::uuid,%L,%L,60,NULL)',
    (SELECT value->>'room_id' FROM _host),(SELECT value->>'token' FROM _host),'impossible'),
  'P0001','Dificuldade inválida.','invalid difficulty is rejected'
);
SELECT * FROM finish();
ROLLBACK;
