create or replace function public.atina_start_mime_round(p_room_id uuid,p_token text,p_round_number integer,p_representative_id uuid,p_duration_seconds integer)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare
 v_host public.atina_room_players%rowtype; v_rep public.atina_room_players%rowtype;
 v_room public.atina_rooms%rowtype; v_card private.atina_mime_cards%rowtype;
 v_state jsonb; v_total integer;
begin
 select * into v_host from public.atina_room_players
 where room_id=p_room_id and token_hash=encode(extensions.digest(coalesce(p_token,''),'sha256'),'hex');
 if not found or not v_host.is_host then raise exception 'Só o anfitrião pode preparar uma ronda de Mímicas.'; end if;
 if p_duration_seconds is null or p_duration_seconds not in (0,60,90) then raise exception 'Duração inválida.'; end if;
 select * into v_room from public.atina_rooms where id=p_room_id for update;
 if not found or v_room.status<>'playing' then raise exception 'A sala não está ativa.'; end if;
 select * into v_rep from public.atina_room_players where id=p_representative_id and room_id=p_room_id;
 if not found then raise exception 'Representante inválido.'; end if;
 select count(*) into v_total from private.atina_mime_cards;
 if p_round_number is null or p_round_number<0 or p_round_number>=v_total then raise exception 'Não existem mais rondas.'; end if;
 if p_round_number=0 then
  if coalesce(v_room.game_state->>'mode','')='mimicas' then raise exception 'A partida de Mímicas já começou.'; end if;
 else
  if coalesce(v_room.game_state->>'mode','')<>'mimicas'
     or coalesce((v_room.game_state->>'round')::integer,-1)<>p_round_number-1
     or coalesce((v_room.game_state->>'locked')::boolean,false)=false then
   raise exception 'A ronda anterior ainda não terminou.';
  end if;
 end if;
 select c.* into v_card from private.atina_mime_cards c
 where not exists(select 1 from private.atina_mime_secrets x where x.room_id=p_room_id and x.card_id=c.id)
 order by random() limit 1;
 if not found then select * into v_card from private.atina_mime_cards order by random() limit 1; end if;
 insert into private.atina_mime_secrets(room_id,round_number,card_id,representative_id,word)
 values(p_room_id,p_round_number,v_card.id,v_rep.id,v_card.word)
 on conflict(room_id,round_number) do update set card_id=excluded.card_id,representative_id=excluded.representative_id,word=excluded.word,created_at=now();
 v_state:=jsonb_build_object(
  'mode','mimicas','round',p_round_number,'total_rounds',v_total,
  'representative_id',v_rep.id,'representative_name',v_rep.nickname,
  'team_label',v_rep.team_label,'category',v_card.category,'clues',v_card.clues,
  'clue_index',0,'duration_seconds',p_duration_seconds,'started',false,
  'locked',false,'deadline',0,'revision',coalesce((v_room.game_state->>'revision')::integer,0)+1
 );
 update public.atina_rooms set game_state=v_state,state_version=state_version+1 where id=p_room_id;
 return v_state;
end;
$$;

create or replace function public.atina_get_mime_secret(p_room_id uuid,p_token text)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare v_player public.atina_room_players%rowtype; v_state jsonb; v_word text;
begin
 select * into v_player from public.atina_room_players
 where room_id=p_room_id and token_hash=encode(extensions.digest(coalesce(p_token,''),'sha256'),'hex');
 if not found then raise exception 'Sessão da sala inválida.'; end if;
 select game_state into v_state from public.atina_rooms where id=p_room_id and status='playing';
 if not found or coalesce(v_state->>'mode','')<>'mimicas' then raise exception 'Não existe uma ronda de Mímicas ativa.'; end if;
 if coalesce(v_state->>'representative_id','')<>v_player.id::text then raise exception 'Só o representante pode ver a palavra secreta.'; end if;
 select word into v_word from private.atina_mime_secrets
 where room_id=p_room_id and round_number=(v_state->>'round')::integer and representative_id=v_player.id;
 if v_word is null then raise exception 'Palavra secreta indisponível.'; end if;
 return jsonb_build_object('word',v_word);
end;
$$;

create or replace function public.atina_resolve_mime_round(p_room_id uuid,p_token text,p_correct boolean,p_points integer,p_reason text)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare
 v_host public.atina_room_players%rowtype; v_room public.atina_rooms%rowtype;
 v_state jsonb; v_word text; v_team text; v_rep uuid; v_round integer; v_delta integer:=0;
begin
 select * into v_host from public.atina_room_players
 where room_id=p_room_id and token_hash=encode(extensions.digest(coalesce(p_token,''),'sha256'),'hex');
 if not found or not v_host.is_host then raise exception 'Só o anfitrião pode terminar a ronda.'; end if;
 select * into v_room from public.atina_rooms where id=p_room_id and status='playing' for update;
 if not found then raise exception 'A partida não está ativa.'; end if;
 v_state:=v_room.game_state;
 if coalesce(v_state->>'mode','')<>'mimicas' or coalesce((v_state->>'locked')::boolean,false) then raise exception 'A ronda já terminou.'; end if;
 if p_reason is null or p_reason not in ('correct','pass','timeout') then raise exception 'Motivo inválido.'; end if;
 if p_correct and p_reason<>'correct' then raise exception 'Resultado inválido.'; end if;
 if p_correct and coalesce((v_state->>'deadline')::bigint,0)>0
  and (v_state->>'deadline')::bigint<floor(extract(epoch from clock_timestamp())*1000)::bigint then
  raise exception 'O tempo desta ronda terminou.';
 end if;
 if p_points is null or p_points<0 or p_points>60 then raise exception 'Pontuação inválida.'; end if;
 v_round:=(v_state->>'round')::integer; v_rep:=(v_state->>'representative_id')::uuid;
 v_team:=nullif(v_state->>'team_label','');
 select word into v_word from private.atina_mime_secrets where room_id=p_room_id and round_number=v_round;
 if v_word is null then raise exception 'Palavra secreta indisponível.'; end if;
 if p_correct then
  v_delta:=p_points;
  if v_team is not null then
   update public.atina_room_players set score=score+v_delta where room_id=p_room_id and team_label=v_team;
   insert into public.atina_room_answers(room_id,player_id,challenge_index,is_correct,points)
   select p_room_id,id,v_round,true,v_delta from public.atina_room_players where room_id=p_room_id and team_label=v_team;
  else
   update public.atina_room_players set score=score+v_delta where room_id=p_room_id and id<>v_rep;
   insert into public.atina_room_answers(room_id,player_id,challenge_index,is_correct,points)
   select p_room_id,id,v_round,true,v_delta from public.atina_room_players where room_id=p_room_id and id<>v_rep;
  end if;
 end if;
 v_state:=jsonb_set(v_state,'{locked}','true'::jsonb,true);
 v_state:=jsonb_set(v_state,'{deadline}','0'::jsonb,true);
 v_state:=jsonb_set(v_state,'{answer}',to_jsonb(v_word),true);
 v_state:=jsonb_set(v_state,'{correct}',to_jsonb(p_correct),true);
 v_state:=jsonb_set(v_state,'{points_awarded}',to_jsonb(v_delta),true);
 v_state:=jsonb_set(v_state,'{feedback}',to_jsonb(case when p_correct then 'Acertaram! +'||v_delta||' pontos.' else case p_reason when 'timeout' then 'Tempo esgotado.' else 'Palavra passada.' end end),true);
 v_state:=jsonb_set(v_state,'{revision}',to_jsonb(coalesce((v_state->>'revision')::integer,0)+1),true);
 update public.atina_rooms set game_state=v_state,state_version=state_version+1 where id=p_room_id;
 return v_state;
end;
$$;

create or replace function public.atina_finish_mime_room(p_room_id uuid,p_token text)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare
 v_host public.atina_room_players%rowtype; v_room public.atina_rooms%rowtype;
 v_state jsonb; v_results jsonb;
begin
 select * into v_host from public.atina_room_players
 where room_id=p_room_id and token_hash=encode(extensions.digest(coalesce(p_token,''),'sha256'),'hex');
 if not found or not v_host.is_host then raise exception 'Só o anfitrião pode finalizar a partida.'; end if;
 select * into v_room from public.atina_rooms where id=p_room_id for update;
 if not found then raise exception 'Sala não encontrada.'; end if;
 v_state:=v_room.game_state;
 if v_room.status<>'playing' or coalesce(v_state->>'mode','')<>'mimicas'
  or coalesce((v_state->>'locked')::boolean,false)=false
  or (v_state->>'round')::integer<(v_state->>'total_rounds')::integer-1 then
  raise exception 'A partida ainda não terminou.';
 end if;
 insert into public.atina_room_results(room_id,player_id,nickname,team_label,score)
 select p_room_id,p.id,p.nickname,p.team_label,p.score from public.atina_room_players p where p.room_id=p_room_id
 on conflict(room_id,player_id) do update set nickname=excluded.nickname,team_label=excluded.team_label,score=excluded.score,completed_at=now();
 select coalesce(jsonb_agg(jsonb_build_object('nickname',nickname,'team',team_label,'score',score) order by score desc),'[]'::jsonb)
 into v_results from public.atina_room_results where room_id=p_room_id;
 v_state:=jsonb_set(v_state,'{finished}','true'::jsonb,true);
 v_state:=jsonb_set(v_state,'{revision}',to_jsonb(coalesce((v_state->>'revision')::integer,0)+1),true);
 update public.atina_rooms set status='finished',game_state=v_state,state_version=state_version+1 where id=p_room_id;
 return jsonb_build_object('finished',true,'results',v_results,'game_state',v_state);
end;
$$;

