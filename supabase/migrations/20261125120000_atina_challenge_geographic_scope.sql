begin
  if not exists (
    select 1
      from pg_constraint
     where conrelid = 'private.atina_challenges'::regclass
       and conname = 'atina_challenges_geographic_scope_check'
  ) then
    alter table private.atina_challenges
      add constraint atina_challenges_geographic_scope_check
      check (geographic_scope in ('Portugal', 'Internacional', 'Universal'));
  end if;
end;
$$;

