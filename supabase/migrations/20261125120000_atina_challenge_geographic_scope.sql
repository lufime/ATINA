do $$
declare
  v_total integer;
  v_classified integer;
  v_invalid integer;
begin
  select count(*),
         count(*) filter (where geographic_scope is not null),
         count(*) filter (where geographic_scope not in ('Portugal', 'Internacional', 'Universal'))
    into v_total, v_classified, v_invalid
    from private.atina_challenges;

  if v_total <> 1089 then
    raise exception 'Expected 1089 challenge rows, found %.', v_total;
  end if;
  if v_classified <> v_total then
    raise exception 'Geographic classification incomplete: % of % rows classified.', v_classified, v_total;
  end if;
  if v_invalid <> 0 then
    raise exception 'Found % invalid geographic classifications.', v_invalid;
  end if;
end;
$$;

